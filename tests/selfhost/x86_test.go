// stage1/src/x86.origin is held to internal/x86, and the oracle needs no invention at all:
// an encoder is right when the bytes are right. Both sides perform the same sequence of
// calls and the bytes are compared.
//
// The table is not a cross product for its own sake. Every instruction appears at least
// twice -- once with low registers and once with high ones, which is what decides the REX
// prefix -- and the operand shapes that are the real risk surface are covered exhaustively:
// every memory base and displacement class (rsp and r12 need a SIB byte; rbp and r13 have
// no disp-less form, because that encoding slot means RIP-relative), every condition, every
// immediate class, every shift count class, and a label reference in each direction.
//
// The two tables are written to be read side by side: goEncoding below and
// testdata/x86_driver.origin perform the same calls in the same order. A divergence in the
// *order* shows up as a byte difference like any other, which is the point -- there is no
// third description of what the sequence is supposed to be.

