// TestStage1EncoderMatchesTheGoEncoder builds a package of stage1's encoder plus the driver
// beside it, runs it on every engine, and compares the bytes.
func TestStage1EncoderMatchesTheGoEncoder(t *testing.T) {
	want := hexLines(goEncoding(t))

	dir := t.TempDir()
	writeEncoderPackage(t, dir)

	// Every engine, because the encoder is Origin and has to encode the same on all three.
	// It is one small program with no input, so none of them needs a stride.
	engines := []struct {
		name   string
		engine driver.Engine
		level  opt.Level
	}{
		{"native-O2", driver.Native, opt.O2},
		{"native-O0", driver.Native, opt.O0},
		{"vm-O2", driver.VM, opt.O2},
		{"interpreter", driver.Interpreter, opt.O0},
	}
	for _, e := range engines {
		t.Run(e.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := runStage1(t, dir, e.engine, e.level, &stdout, &stderr); code != 0 {
				t.Fatalf("the encoder driver exited %d\nstderr:\n%s", code, stderr.String())
			}
			if stderr.Len() > 0 {
				t.Fatalf("the encoder driver wrote to stderr:\n%s", stderr.String())
			}
			got := strings.Split(strings.TrimSuffix(stdout.String(), "\n"), "\n")
			if len(got) != len(want) {
				t.Errorf("stage1 printed %d lines of bytes, the Go encoder %d", len(got), len(want))
			}
			bad := 0
			for i := 0; i < len(got) && i < len(want); i++ {
				if got[i] != want[i] {
					bad++
					if bad <= 8 {
						t.Errorf("byte %d onward:\n  stage1: %s\n  go:     %s", i*32, got[i], want[i])
					}
				}
			}
			if bad > 8 {
				t.Errorf("... and %d more lines differ", bad-8)
			}
			if bad == 0 && len(got) == len(want) {
				t.Logf("%d bytes identical", len(goEncoding(t)))
			}
		})
	}
}

// hexLines renders bytes the way the driver prints them: lowercase hex, thirty-two to a
// line, so a divergence names a byte offset rather than one enormous line.
func hexLines(code []byte) []string {
	const digits = "0123456789abcdef"
	var out []string
	var line []byte
	for i, b := range code {
		line = append(line, digits[b>>4], digits[b&15])
		if (i+1)%32 == 0 {
			out = append(out, string(line))
			line = line[:0]
		}
	}
	if len(line) > 0 {
		out = append(out, string(line))
	}
	return out
}

// writeEncoderPackage assembles a package of stage1's own x86.origin and the driver that
// exercises it -- the same shape the lexer and parser differentials use, so that one module
// can be run without building the whole compiler around it.
func writeEncoderPackage(t *testing.T, dir string) {
	t.Helper()
	src := filepath.Join(dir, "src")
	if err := os.MkdirAll(src, 0o755); err != nil {
		t.Fatal(err)
	}
	root := testutil.RepoRoot(t)
	for _, name := range []string{"x86.origin"} {
		data, err := os.ReadFile(filepath.Join(root, "stage1", "src", name))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(src, name), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	main, err := os.ReadFile(filepath.Join(root, "tests", "selfhost", "testdata", "x86_driver.origin"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(src, "main.origin"), main, 0o644); err != nil {
		t.Fatal(err)
	}
}
